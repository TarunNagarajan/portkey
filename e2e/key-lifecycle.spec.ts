import { readFile } from 'node:fs/promises';
import { expect, test } from '@playwright/test';
test('late members automatically read earlier files and organizer recovery preserves room access', async ({ page, browser }) => {
  test.setTimeout(120_000);
  await page.goto('/');
  await page.getByLabel('Room title').fill('Key lifecycle workshop');
  await page.getByRole('button', { name: 'Create draft' }).click();
  await page.getByRole('button', { name: 'Open room', exact: true }).click();
  await expect(page.locator('.join-link')).toHaveAttribute('href', /#key=/);
  const invite = await page.locator('.join-link').getAttribute('href');
  await page.getByLabel('Choose a file (up to 250 MiB)').setInputFiles({ name: 'earlier.txt', mimeType: 'text/plain', buffer: Buffer.from('Earlier encrypted material') });
  await page.getByRole('button', { name: 'Encrypt and share with room' }).click();
  await expect(page.getByText(/All approved members can download it/)).toBeVisible();
  const studentContext = await browser.newContext(), student = await studentContext.newPage();
  const recoveredContext = await browser.newContext();
  try {
    await student.goto(invite!); await student.getByLabel('Your label').fill('Late student');
    await student.getByRole('button', { name: 'Request access', exact: true }).click();
    const row = page.getByRole('row').filter({ hasText: 'Late student' });
    await row.getByRole('button', { name: 'Approve', exact: true }).click();
    await student.getByRole('link', { name: 'Enter room' }).click();
    await expect(student.getByText('earlier.txt', { exact: true })).toBeVisible();
    await expect(page.getByRole('button', { name: 'Grant access to earlier files' })).toHaveCount(0);
    await page.locator('details.security-settings summary').click();
    await page.getByRole('button', { name: 'Rotate encryption key', exact: true }).click();
    await expect(page.getByText('Organizer key replaced.', { exact: false })).toBeVisible();
    const nextInvite = await page.locator('.join-link').getAttribute('href'); expect(nextInvite).not.toBe(invite);
    await student.goto(nextInvite!); await student.getByRole('link', { name: 'Enter room' }).click();
    await expect(student.getByText('earlier.txt', { exact: true })).toBeVisible();
    await page.locator('details.security-settings summary').click();
    await page.getByLabel('Backup passphrase').fill('a new owner rotation backup password');
    const backupEvent = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Download encrypted key backup' }).click();
    const backup = await backupEvent, backupText = await readFile((await backup.path())!, 'utf8');
    const section = page.getByRole('heading', { name: 'Ownership recovery', exact: true }).locator('..');
    await section.getByRole('button', { name: 'Create ownership recovery code' }).click();
    const code = await section.locator('code').innerText();
    const recovered = await recoveredContext.newPage(); await recovered.goto('/recover');
    await recovered.getByLabel('Ownership recovery code').fill(code);
    await recovered.getByRole('button', { name: 'Recover ownership', exact: true }).click();
    await expect(recovered.getByText('Restore your organizer backup under Security and recovery', { exact: false })).toBeVisible();
    await recovered.getByLabel('Backup passphrase').fill('a new owner rotation backup password');
    await recovered.getByLabel('Restore key backup (.json)').setInputFiles({ name: 'rotated-backup.json', mimeType: 'application/json', buffer: Buffer.from(backupText) });
    await expect(recovered.getByText('earlier.txt', { exact: true })).toBeVisible();
    const path = new URL(recovered.url()).pathname;
    expect((await page.request.get(`/api${path}/members`)).status()).toBe(403);
    await recovered.screenshot({ path: '../outputs/Portkey_Recovery_Desktop.png', fullPage: true });
  } finally { await studentContext.close(); await recoveredContext.close(); }
});
